// Позиционное соответствие ЙЦУКЕН и QWERTY: клавиша с русской буквой означает
// команду, закреплённую за её физической позицией на клавиатуре.
//
// Нужно двум местам сразу. Виму — чтобы `d`, `w`, `j` работали, не переключая
// раскладку. Раскладке приложения — чтобы `Cmd+,` не превращался в `Cmd+б`, а
// `j`/`k` в списке — в `о`/`л`. Таблица одна на оба случая: разъехавшись, они
// дали бы взаимно противоречащее поведение в соседних контекстах.

// Ряды клавиатуры в одном и том же порядке.
const EN = "qwertyuiop[]asdfghjkl;'zxcvbnm,./";
const RU = "йцукенгшщзхъфывапролджэячсмитьбю.";

const EN_SHIFT = "QWERTYUIOP{}ASDFGHJKL:\"ZXCVBNM<>?";
const RU_SHIFT = "ЙЦУКЕНГШЩЗХЪФЫВАПРОЛДЖЭЯЧСМИТЬБЮ,";

// В формате langmap запятая, точка с запятой и обратный слеш экранируются.
const esc = (s: string) => s.replace(/([\\,;])/g, "\\$1");

if (EN.length !== RU.length || EN_SHIFT.length !== RU_SHIFT.length) {
  throw new Error("langmap: ряды разной длины, парсер молча выбросит их целиком");
}

export const RU_LANGMAP = `${esc(RU)};${esc(EN)},${esc(RU_SHIFT)};${esc(EN_SHIFT)}`;

/** Только кириллица: латиница и знаки в переводе не нуждаются. */
const cyrillic = /[\u0400-\u04FF]/;

/**
 * Русский символ → латинский с той же физической клавиши.
 *
 * Собирается из тех же рядов, что и строка для вима: держать вторую таблицу
 * руками значит однажды поправить одну и забыть другую.
 *
 * Некириллические символы из рядов пропускаются, и это не мелочь. В русском
 * ряду физическая клавиша `/` даёт `.`, а с шифтом `,` — те же самые символы,
 * что и в латинском, но на другой позиции. Переведи их — и обычная запятая
 * превратится в `?`, то есть Cmd+, перестанет работать на английской
 * раскладке ровно ради того, чтобы заработать на русской.
 *
 * Цена: сочетание на физической клавише `/` при ЙЦУКЕН не сработает — она
 * шлёт `.`, и отличить это от настоящей точки нечем. Таких привязок нет.
 */
const positional = new Map<string, string>();
for (let i = 0; i < RU.length; i++) {
  if (cyrillic.test(RU[i])) positional.set(RU[i], EN[i]);
}
for (let i = 0; i < RU_SHIFT.length; i++) {
  if (cyrillic.test(RU_SHIFT[i])) positional.set(RU_SHIFT[i], EN_SHIFT[i]);
}

/**
 * latinKey приводит нажатие к латинской раскладке по физической позиции.
 *
 * Незнакомый символ возвращается как есть: таблица покрывает ЙЦУКЕН, а не все
 * раскладки мира, и ломать остальное ей незачем.
 */
export function latinKey(key: string): string {
  return positional.get(key) ?? key;
}
