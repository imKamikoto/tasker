// а node без расширения соседний файл не найдёт.
import type { Filter } from "./components/Sidebar.tsx";

/**
 * scopeLabel — как называется то, что сейчас показано в списке.
 *
 * Нужно потому, что выбранное видно только в сайдбаре, а сайдбар прячется
 * (⌘/). Без подписи над списком со свёрнутым сайдбаром невозможно ответить на
 * вопрос «а это вообще что за заметки».
 *
 * Чистой функцией и с тестами, а не выражением внутри разметки: вариантов
 * шесть, у двух из них есть особые случаи, и проверять их таблицей дешевле,
 * чем щёлкать по сайдбару руками.
 */
export function scopeLabel(filter: Filter): string {
  switch (filter.kind) {
    case "active":
      return "Активные";
    case "all":
      return "Все заметки";
    case "agent":
      return "От агента";
    case "trash":
      return "Корзина";
    case "notebook":
      // У корня хранилища имени нет — там же, где в дереве, он зовётся
      // «Корнем». Вложенный показывается целиком: «Баги» без «Работа/»
      // не отвечает на вопрос, какие это баги.
      return filter.path === "" ? "Корень" : filter.path;
    case "tags":
      // Несколько тегов соединяются через И — это делает язык запросов, и
      // подпись обязана читаться так же, а не списком через запятую.
      return filter.names.map((name) => `#${name}`).join(" + ");
  }
}
