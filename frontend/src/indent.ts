/**
 * Считать ли нажатие Tab отступом блока, а не символом табуляции.
 *
 * Правило одно: выделение задевает больше одной строки. Тогда «сдвинуть
 * вправо» — единственное осмысленное прочтение, а вставка табуляции стёрла бы
 * выделенное. Выделение внутри одной строки (или пустое) остаётся за набором:
 * там Tab обязан печатать.
 *
 * Отдельной функцией от команды редактора, потому что вся суть здесь — в
 * границах: пустое выделение, каретка на стыке строк, несколько курсоров.
 * Проверять это таблицей дешевле, чем щёлкать в окне.
 */
export type LineRange = { fromLine: number; toLine: number };

export function spansLines(ranges: LineRange[]): boolean {
  return ranges.some((range) => range.fromLine !== range.toLine);
}
