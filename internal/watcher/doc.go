// Package watcher замечает изменения в vault, сделанные не нами: правку файла
// внешним редактором, заметку, созданную tasker-mcp при закрытом приложении.
//
// Watcher — оптимизация задержки, а не источник правды: периодическая сверка
// ловит всё, что он проспал, поэтому терять события здесь не страшно, а врать
// про них страшно. См. SPEC §5.3.
//
// На macOS под fsnotify лежит kqueue. Рекурсии в нём нет, поэтому дерево
// обходится самостоятельно, а на каждый созданный каталог наблюдение
// довешивается. Наблюдение вешается на каталоги, но fsnotify внутри себя
// открывает дескриптор ещё и на каждый файл — иначе правка содержимого была бы
// не видна. Замеры и следствия описаны в SPEC §5.3.
//
// Пакет не импортирует Wails — см. CLAUDE.md, инвариант 4.
